// ─── Helper Functions ───

export function getByCategory(category: MenuCategory): MenuItem[] {
  return menuItems.filter((item) => item.category === category);
}

export function getFeatured(): MenuItem[] {
  return menuItems.filter((item) => item.featured && item.available);
}

export function getAllDietary(tag: DietaryTag): MenuItem[] {
  return menuItems.filter((item) => item.dietary.includes(tag) && item.available);
}
